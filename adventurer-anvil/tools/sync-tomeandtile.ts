// Copies Tome & Tile's generated contract types into Anvil, for the Tome & Tile export, and records where they came
// from: the Tome & Tile commit and each file's SHA-256. A test checks the copies still match those hashes, so they are
// never edited by hand. Run again when Tome & Tile's Creature contract changes.
//
// Run from adventurer-anvil/frontend: npm run sync:tomeandtile -- <path to a Tome & Tile checkout>
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** The generated files the Creature message needs (it imports common and scene). */
export const FILES = ["common_pb.ts", "scene_pb.ts", "creature_pb.ts"];
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const GEN_DIR = join(ROOT, "frontend/src/systems/dnd5e-2014/export/tomeandtile/gen");

export const sha256 = (text: string) => createHash("sha256").update(text).digest("hex");

function main() {
  const repo = process.argv[2];
  if (!repo) {
    console.error("Give the path to a Tome & Tile checkout: npm run sync:tomeandtile -- ../../TomeAndTile");
    process.exit(1);
  }
  const from = join(repo, "contracts/ts/src/gen/tomeandtile/v1");
  const commit = execFileSync("git", ["-C", repo, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
  mkdirSync(GEN_DIR, { recursive: true });
  const rows: string[] = [];
  for (const f of FILES) {
    const text = readFileSync(join(from, f), "utf8").replace(/\r\n/g, "\n");
    writeFileSync(join(GEN_DIR, f), text);
    rows.push(`| \`${f}\` | \`${sha256(text)}\` |`);
  }
  writeFileSync(join(GEN_DIR, "SOURCE.md"), `# Tome & Tile contract types (copied)

Generated by Tome & Tile from its Protobuf contracts (\`contracts/proto/tomeandtile/v1/\`) and copied here unchanged by
\`tools/sync-tomeandtile.ts\`. Do not edit them: change the contract in Tome & Tile, then run the script again.

- Repository: https://github.com/Henry-theBinaryBuddies/TomeAndTile
- Commit: \`${commit}\`
- Licence: AGPL-3.0-only (Tome & Tile's, and Adventurer Anvil's)

| File | SHA-256 |
|---|---|
${rows.join("\n")}
`);
  console.log(`Copied ${FILES.length} files from ${commit.slice(0, 7)}.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
